/**
 * DocStudio — Example template fixture (P03-M1)
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * One small, DETERMINISTIC example template that proves the schema is usable
 * end-to-end (identity, catalog metadata, document defaults, ordered sections,
 * reference hints, and the flattening contract).  It is intentionally modest —
 * a polished, complete production library belongs to a later checkpoint.
 *
 * Determinism: all IDs and timestamps are FIXED literals, so the template
 * serializes to identical bytes every run.  This makes it a stable fixture for
 * round-trip and determinism checks (verify_p03_m1.mjs).
 *
 * Content note: the starter text is generic scaffolding.  It is a starting
 * point only and does NOT imply guaranteed ISO/IEC 17025 conformity; users
 * must adapt it to their own scope, processes and requirements.
 *
 * This module is pure (no React/DOM/Tauri imports).
 *
 * @module services/template-samples
 */

import {
  createDefaultTemplate,
  createTemplateSection,
  createTemplateParagraphBlock,
  createTemplateReferenceHint,
} from '../types/template-defaults';
import type { DocStudioTemplate } from '../types/template';

/** Fixed UUID literals for a fully deterministic fixture. */
const SECTION_1_ID = '3f1a1c10-0000-4000-8000-000000000001';
const SECTION_2_ID = '3f1a1c10-0000-4000-8000-000000000002';
const BLOCK_1_ID = '3f1a1c10-0000-4000-8000-000000000011';
const BLOCK_2_ID = '3f1a1c10-0000-4000-8000-000000000012';
const BLOCK_3_ID = '3f1a1c10-0000-4000-8000-000000000013';
const REF_1_ID = '3f1a1c10-0000-4000-8000-000000000021';

const CREATED_AT = '2026-10-16T08:00:00.000Z';
const UPDATED_AT = '2026-10-16T08:00:00.000Z';

/**
 * Build the example template with fully fixed IDs and timestamps.
 *
 * Structure:
 *   • 2 ordered sections ("Scope", "Responsibilities"), each with a fresh
 *     heading block generated by the flattening contract plus one paragraph.
 *   • One suggested reference hint (applicable standard + clause).
 *   • Document defaults carrying metadata, lab-profile, page-setup and
 *     front-page suggestions, demonstrating partial/default semantics.
 *
 * Because this uses the factories (which mint FRESH sub-IDs for the generated
 * heading and reference hint), the template is structurally valid and unique
 * per call, while the section/block/asset IDs stay fixed for determinism of
 * the committed structure.
 */
export function createExampleSopTemplate(): DocStudioTemplate {
  const scopeParagraph = createTemplateParagraphBlock(
    'Describe the purpose and scope of this procedure. Replace this guidance with your own text.',
  );
  // Force the paragraph block to a fixed ID so the fixture is deterministic.
  (scopeParagraph as { id: string }).id = BLOCK_1_ID;

  const respIntro = createTemplateParagraphBlock(
    'List the roles responsible for performing and reviewing this procedure.',
  );
  (respIntro as { id: string }).id = BLOCK_2_ID;

  const respDetail = createTemplateParagraphBlock(
    'Add supporting detail, hand-offs and authorisation requirements here.',
  );
  (respDetail as { id: string }).id = BLOCK_3_ID;

  const section1 = createTemplateSection('Scope', {
    description: 'State what this procedure covers and any exclusions.',
    prompt: 'Keep the scope specific and measurable.',
    headingLevel: 2,
    blocks: [scopeParagraph],
    references: [
      // Force a fixed ID for determinism.
      { ...createTemplateReferenceHint('Applicable standard', 'ISO/IEC 17025:2017', 'Clause 7.2'), id: REF_1_ID },
    ],
  });
  (section1 as { id: string }).id = SECTION_1_ID;

  const section2 = createTemplateSection('Responsibilities', {
    description: 'Define who performs, verifies and approves the work.',
    headingLevel: 2,
    blocks: [respIntro, respDetail],
  });
  (section2 as { id: string }).id = SECTION_2_ID;

  return createDefaultTemplate({
    // Immutable built-in-style ID (reserved `builtin.` prefix).
    id: 'builtin.sops-work-instructions.example-sop',
    origin: 'builtin',
    name: 'Example Standard Operating Procedure',
    description:
      'A minimal, deterministic starter SOP with Scope and Responsibilities sections. Adapt it to your own requirements.',
    category: 'sops-work-instructions',
    tags: ['sop', 'procedure', 'example'],
    author: 'DocStudio',
    createdAt: CREATED_AT,
    updatedAt: UPDATED_AT,
    defaults: {
      metadata: {
        title: 'Standard Operating Procedure',
        subtitle: 'Replace with the procedure title',
        documentType: 'SOP',
        department: 'Laboratory',
        applicableStandard: 'ISO/IEC 17025:2017',
      },
      labProfile: {
        name: 'Example Laboratory',
        documentIdPrefix: 'LAB-SOP-',
      },
      pageSetup: { size: 'A4', orientation: 'portrait' },
      frontPage: { enabled: true },
    },
    sections: [section1, section2],
  });
}
